function changeLang(language) {
    localStorage.setItem("lang", language)
    console.log(language)
    const imgChanges = document.querySelectorAll('.selected img')
    imgChanges.forEach(imgChange => {
        imgChange.src = imgChange.src.slice(0,-6) + `${language}.svg`
    })
    const pageText = document.querySelectorAll('[id]')
    // console.log(pageText)

    pageText.forEach((el) => {
        const key = el.id

        if (translations[language] && translations[language][key]) {
            // console.log(`Меняем для ${key} ${language}`)
            if (el.nodeName == "TEXTAREA") {
                el.placeholder = translations[language][key];
            } else {
                el.textContent = translations[language][key];
                el.innerHTML = translations[language][key];
            }
        }
    })
}

document.addEventListener('DOMContentLoaded', function() {
    const userLanguage = navigator.language || navigator.userLanguage;

    let lang = localStorage.getItem('lang')
    if (lang){
        console.log("local value: ", lang)
        return changeLang(lang)
    }

    if (userLanguage.startsWith("ru")) {
        changeLang('ru')
    } else if (userLanguage.startsWith("zh")) {
        changeLang('cn')
    } else {
        changeLang('us')
    }
});
